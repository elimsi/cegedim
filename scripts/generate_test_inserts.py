import os
import glob

scenarios_dir = 'c:/Users/ismai/OneDrive/Desktop/internships/Stage cegedim/cetip-bordereau-workflow/data/test_scenarios'
output_file = os.path.join(scenarios_dir, 'insert_test_scenarios.sql')

# Get all test scenario txt files
txt_files = glob.glob(os.path.join(scenarios_dir, 'test*.txt'))

with open(output_file, 'w', encoding='utf-8') as f_out:
    f_out.write("-- Autogenerated insert script for test scenarios\n\n")
    
    for txt_file in txt_files:
        basename = os.path.basename(txt_file)
        
        # Change the extension from .txt to .ok as requested by the user
        filename_ok = basename.replace('.txt', '.ok')
        
        with open(txt_file, 'r', encoding='utf-8') as f_in:
            content = f_in.read()
            
            # Escape single quotes for SQL insertion
            content_escaped = content.replace("'", "''")
            
            # Write the INSERT statement
            sql = f"""INSERT INTO bordereaux_inbox (nom_fichier, contenu, statut) VALUES (
'{filename_ok}',
'{content_escaped}',
'EN_ATTENTE'
);\n\n"""
            f_out.write(sql)
            
print(f"Successfully generated {output_file} with {len(txt_files)} scenarios.")
